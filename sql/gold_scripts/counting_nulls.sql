SELECT
    COUNT(*) AS total_rows,
    COUNT(DISTINCT order_id) AS unique_orders,
    COUNT(*) FILTER (WHERE is_delayed IS NULL) AS null_target,
    COUNT(*) FILTER (WHERE purchase_month IS NULL) AS null_purchase_month,
    COUNT(*) FILTER (WHERE purchase_day_of_week IS NULL) AS null_purchase_dow,
    COUNT(*) FILTER (WHERE purchase_hour IS NULL) AS null_purchase_hour,
    COUNT(*) FILTER (WHERE approval_time_hours IS NULL) AS null_approval_time,
    COUNT(*) FILTER (WHERE estimated_delivery_days IS NULL) AS null_estimated_days,
    COUNT(*) FILTER (WHERE item_count IS NULL) AS null_item_count,
    COUNT(*) FILTER (WHERE unique_product_count IS NULL) AS null_unique_products,
    COUNT(*) FILTER (WHERE seller_count IS NULL) AS null_seller_count,
    COUNT(*) FILTER (WHERE total_price IS NULL) AS null_price,
    COUNT(*) FILTER (WHERE total_freight IS NULL) AS null_freight,
    COUNT(*) FILTER (WHERE total_weight_g IS NULL) AS null_weight,
    COUNT(*) FILTER (WHERE total_volume_cm3 IS NULL) AS null_volume,
    COUNT(*) FILTER (WHERE distance_km IS NULL) AS null_distance,
    COUNT(*) FILTER (WHERE shipping_state_type IS NULL) AS null_shipping_state,
    COUNT(*) FILTER (WHERE payment_count IS NULL) AS null_payment_count,
    COUNT(*) FILTER (WHERE payment_type_count IS NULL) AS null_payment_types,
    COUNT(*) FILTER (WHERE max_installments IS NULL) AS null_installments,
    COUNT(*) FILTER (WHERE category_count IS NULL) AS null_category_count,
    COUNT(*) FILTER (WHERE main_product_category IS NULL) AS null_main_category
FROM gold.delivery_delay;